// Holds the shared footer workflow to what lets every repository call it safely: only callable, a token that writes pull
// requests and nothing else, the script it runs equal to scripts/strip-pr-footer.mjs, and that script removing the footer
// and nothing more.

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

import { callerProblems } from "../scripts/check-callers.mjs";
import { inlined } from "../scripts/inline-rollback-guard.mjs";
import { stripFooter } from "../scripts/strip-pr-footer.mjs";

const text = readFileSync(new URL("../.github/workflows/pr-footer.yml", import.meta.url), "utf8").replace(/\r\n/g, "\n");
const code = text.split("\n").filter((line) => !/^\s*#/.test(line)).join("\n");

test("it is only callable", () => {
  const on = text.slice(text.indexOf("\non:\n"), text.indexOf("\npermissions:"));
  assert.match(on, /workflow_call:/);
  assert.doesNotMatch(on, /workflow_dispatch|pull_request|push:|schedule:/);
});

test("the token writes pull requests and nothing else, and no secret is taken", () => {
  assert.match(text, /\npermissions:\n {2}contents: read\n/);
  assert.deepEqual([...code.matchAll(/(\S+): write\b/g)].map((m) => m[1]), ["pull-requests"]);
  assert.doesNotMatch(code, /secrets/);
});

test("a fork's pull request and a push to one are skipped", () => {
  assert.match(code, /github\.event\.pull_request\.head\.repo\.full_name == github\.repository/);
  assert.match(code, /github\.event\.action != 'synchronize'/);
});

test("the script the workflow runs is scripts/strip-pr-footer.mjs byte for byte (regenerate: node scripts/inline-rollback-guard.mjs)", () => {
  const script = readFileSync(new URL("../scripts/strip-pr-footer.mjs", import.meta.url), "utf8");
  assert.equal(inlined(text, "PR_FOOTER"), script);
});

test("PLANT: the connection's footer is removed, whichever link it carries", () => {
  const body = "Before: x.\n\nCloses job_0368576da167.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01Abc)_";
  assert.equal(stripFooter(body), "Before: x.\n\nCloses job_0368576da167.\n");
  assert.equal(stripFooter("Text.\n\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"), "Text.\n");
});

test("the older wording, a bare line and a session link are removed too", () => {
  assert.equal(stripFooter("Text.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01Xyz"), "Text.\n");
  assert.equal(stripFooter("Text.\n_Generated by [Claude Code](https://claude.ai/code)_"), "Text.\n");
});

test("a description with no footer, a rule in the middle, or a mention in prose is left alone", () => {
  assert.equal(stripFooter("Before.\n\n---\n\nAfter."), null);
  assert.equal(stripFooter("We tried Generated by [Claude Code](https://claude.ai/code)_ in the middle.\n\nMore text."), null);
  assert.equal(stripFooter(null), null);
  assert.equal(stripFooter(""), null);
});

test("the example caller passes the pin check and grants the write the workflow needs", () => {
  const caller = readFileSync(new URL("../examples/pr-footer-caller.yml", import.meta.url), "utf8");
  assert.deepEqual(callerProblems(caller), []);
  assert.match(caller, /pull-requests: write/);
  assert.match(caller, /types: \[opened, reopened, edited\]/);
  assert.match(caller, /workflow_dispatch:/);
});
