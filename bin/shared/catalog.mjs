import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { PACKAGES, FEATURES, ASSET_CACHE, BACKUP, EMAIL, CLAUDE_HOOKS } from "./data.mjs";
import { ADVISORIES } from "./advisories.mjs";
import { exportNames } from "./copies.mjs";
import { LINT_SCRIPT, FORMAT_CHECK_SCRIPT } from "./lint.mjs";
import { JOBS, OTHER_JOBS } from "./jobs.mjs";
/** @import { Catalog } from "./config.mjs" */

/**
 * The export catalog: every installed shared package's subpaths and the names each exports.
 * @param {(name: string, repo: string) => string | null} locate the package's directory
 * @returns {{ catalog: Catalog, packages: { label: string, repo: string, version: string, entries: [string, string[]][], bins: string[] }[] }}
 */
export function readCatalog(locate) {
  /** @type {Catalog} */
  const catalog = {};
  const packages = [];
  for (const { name, repo, label } of PACKAGES) {
    const dir = locate(name, repo);
    if (!dir) continue;
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    /** @type {[string, string[]][]} */
    const entries = [];
    const exp =
      typeof manifest.exports === "string" ? { ".": manifest.exports } : (manifest.exports ?? {});
    for (const [sub, target] of Object.entries(exp)) {
      if (sub === "./package.json" || /\.css$|\.json$/.test(sub)) continue;
      if (sub.includes("*")) {
        const base = sub.split("/")[1];
        const comps = existsSync(join(dir, "components"))
          ? readdirSync(join(dir, "components")).filter((c) =>
              statSync(join(dir, "components", c)).isDirectory(),
            )
          : [];
        // Capsomer's behaviors are listed by what each exports (behavior/time's relative, day...), so a site writing its
        // own finds them; the British spelling of the same subpath and the React components stay a list of components.
        if (sub === "./behavior/*") {
          for (const c of comps) {
            const file = moduleFile(dir, JSON.parse(JSON.stringify(target).replaceAll("*", c)));
            if (file) entries.push([`./${base}/${c}`, exportNames(readFileSync(file, "utf8"))]);
          }
          continue;
        }
        entries.push([sub, comps.map((c) => `${base}/${c}`)]);
        continue;
      }
      const file = moduleFile(dir, target);
      const names = file ? exportNames(followReexports(file)) : [];
      entries.push([sub, names]);
      // devkit's exports are test helpers, not site code a site could copy.
      if (repo !== "devkit")
        for (const n of names)
          if (!catalog[n] || catalog[n].endsWith(" .")) catalog[n] = `${label} ${sub}`;
    }
    packages.push({
      label,
      repo,
      version: manifest.version,
      entries,
      bins: Object.keys(manifest.bin ?? {}),
    });
  }
  return { catalog, packages };
}

/** The file that declares a subpath's exports: its types, else its source. */
function moduleFile(/** @type {string} */ dir, /** @type {unknown} */ target) {
  /** @type {any} */
  let t = target;
  while (t && typeof t === "object") t = t.types ?? t.import ?? t.default;
  if (typeof t !== "string") return null;
  const f = join(dir, t);
  const candidates = [
    f,
    f.replace(/\.m?js$/, ".d.mts"),
    f.replace(/\.js$/, ".d.ts"),
    f.replace(/^(.*)\/dist\/(.*)\.d\.ts$/, "$1/src/$2.ts"),
    f.replace(/^(.*)\/dist\/(.*)\.js$/, "$1/src/$2.ts"),
    f.replace(/^(.*)\/dist\/(.*)\.d\.ts$/, "$1/$2.ts"),
  ];
  return candidates.find((c) => existsSync(c) && statSync(c).isFile()) ?? null;
}

/** The module's text with any `export * from` it makes appended. */
function followReexports(/** @type {string} */ file) {
  let src = readFileSync(file, "utf8");
  for (const m of src.matchAll(/export\s+\*\s+from\s+["'](.+?)["']/g)) {
    const r = join(dirname(file), m[1]);
    const hit = [
      r,
      r.replace(/\.m?js$/, ".d.mts"),
      r.replace(/\.js$/, ".ts"),
      r.replace(/\.js$/, ".d.ts"),
    ].find((c) => existsSync(c) && statSync(c).isFile());
    if (hit) src += `\n${readFileSync(hit, "utf8")}`;
  }
  return src;
}

/** The generated list, as markdown. */
export function listMarkdown(/** @type {ReturnType<typeof readCatalog>["packages"]} */ packages) {
  const lines = [
    "# What the shared packages already do",
    "",
    "Generated by `devkit-shared list`; do not edit by hand. Before writing anything a site might share, look here: if a package exports it, import it. `npx devkit-shared` fails a repository that copies one of these, misses a shared feature, or pins an old release.",
    "",
    "## Family features",
    "",
    "| Feature | Needed by | Provided by |",
    "| --- | --- | --- |",
    ...Object.entries(FEATURES).map(
      ([f, { kinds, use }]) => `| ${f} | ${kinds.join(", ")} | ${use} |`,
    ),
    ...Object.entries(ADVISORIES).map(
      ([f, { kinds, use }]) => `| ${f} (a warning) | ${kinds.join(", ")} | ${use} |`,
    ),
    `| backup | any app with a D1 database | ${BACKUP.use} |`,
    `| email | any app with a send_email binding | ${EMAIL.use} |`,
    `| assetCache | any React Router app (/assets/*, and /islands/* with devkit ./islands) | ${ASSET_CACHE.use} |`,
    `| lint | every repository with JavaScript or TypeScript | devkit ./oxlint in a root oxlint.config.ts, the \`lint\` script \`${LINT_SCRIPT}\`, and \`npm run lint\` in CI |`,
    `| format | every repository with JavaScript or TypeScript | devkit ./oxfmt in a root oxfmt.config.ts, the \`format:check\` script \`${FORMAT_CHECK_SCRIPT}\`, and \`npm run format:check\` in CI |`,
    "",
    "## Agent jobs",
    "",
    "Each job has one owner. A site's MCP server that serves a tool for a job it does not own fails `jobs`, read by the tool's name, title and the call it makes, so a renamed copy fails too.",
    "",
    "| Job | Owner | Use |",
    "| --- | --- | --- |",
    ...JOBS.map(
      (j) =>
        `| ${j.job} | ${j.owner} | ${j.use}${j.failsFrom ? ` (a warning until devkit ${j.failsFrom})` : ""} |`,
    ),
    ...OTHER_JOBS.map((j) => `| ${j.job} | ${j.owner} | ${j.use} |`),
  ];
  for (const p of packages) {
    lines.push("", `## ${p.label} ${p.version} (DrDustinEdwards/${p.repo})`, "");
    for (const [sub, names] of p.entries)
      lines.push(
        `- \`${sub}\`: ${names.length ? names.map((n) => `\`${n}\``).join(", ") : "(no named exports)"}`,
      );
    if (p.bins.length) lines.push(`- bins: ${p.bins.map((b) => `\`${b}\``).join(", ")}`);
    if (p.repo === "devkit")
      lines.push(
        `- Claude Code hooks (\`claude/hooks\`, run from \`.claude/settings.json\`, README "The shared Claude Code hooks"): ${CLAUDE_HOOKS.map((h) => `\`${h}\``).join(", ")}`,
      );
  }
  return `${lines.join("\n")}\n`;
}
