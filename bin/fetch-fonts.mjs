#!/usr/bin/env node
// Self-host Google Fonts. Fetches the CSS Google serves a modern browser (woff2, already subset, one `@font-face` per
// family and subset), keeps the subsets listed, downloads each file and writes a stylesheet pointing at the local copies.
// A build-time step: the site makes no runtime call to Google. Re-runnable.
//
//   npx devkit-fetch-fonts                    read .fonts.json
//   npx devkit-fetch-fonts --config <file>
//
// The config:
//
//   { "css_url": "https://fonts.googleapis.com/css2?family=Inter:wght@400..700&display=swap",
//     "subsets": ["latin", "latin-ext"], "dir": "public/fonts", "url_prefix": "/fonts/", "css": "app/fonts.css",
//     "display": "optional", "header": "Self-hosted fonts. Inter (body)." }
//
// `css_url` is required. Defaults: subsets latin and latin-ext, dir `public/fonts`, url_prefix `/fonts/`, css
// `app/fonts.css`, display `optional` (web.dev, "Best practices for fonts": a face that misses the first ~100 ms stays in the
// size-matched fallback, so text never moves once drawn). Each file is named `<family-slug>-<subset>.woff2`; a variable font
// is one file per family and subset, which covers every weight.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { readConfig } from "./site-config.mjs";
import { isMain } from "../node/index.mjs";

// A modern desktop UA makes Google return woff2 with per-subset unicode-range blocks.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36";

/**
 * The faces in Google's CSS, one per subset comment.
 * @param {string} css
 * @param {Set<string>} keep
 */
export function parseFaces(css, keep) {
  const faces = [];
  for (const part of css.split("/* ").slice(1)) {
    const subset = part.slice(0, part.indexOf(" */"));
    if (!keep.has(subset)) continue;
    const body = part.slice(part.indexOf("@font-face"));
    const get = (/** @type {RegExp} */ re, /** @type {string} */ what) => {
      const m = re.exec(body);
      if (!m) throw new Error(`a ${subset} face has no ${what}`);
      return m[1].trim();
    };
    faces.push({
      subset,
      family: get(/font-family:\s*'([^']+)'/, "font-family"),
      weight: get(/font-weight:\s*([^;]+);/, "font-weight"),
      style: get(/font-style:\s*([^;]+);/, "font-style"),
      url: get(/src:\s*url\(([^)]+)\)\s*format\('woff2'\)/, "woff2 src"),
      unicode: get(/unicode-range:\s*([^;]+);/, "unicode-range"),
    });
  }
  return faces;
}

async function main() {
  const { config: c } = readConfig(process.argv.slice(2), ".fonts.json", "fetch-fonts");
  if (typeof c.css_url !== "string" || !c.css_url.startsWith("https://fonts.googleapis.com/")) {
    console.error('fetch-fonts: "css_url" must be an https://fonts.googleapis.com/ URL');
    process.exit(1);
  }
  const keep = new Set(c.subsets ?? ["latin", "latin-ext"]);
  const dir = c.dir ?? "public/fonts";
  const prefix = c.url_prefix ?? "/fonts/";
  const display = c.display ?? "optional";
  const res = await fetch(c.css_url, {
    headers: { "User-Agent": UA },
    signal: AbortSignal.timeout(30_000),
  });
  if (!res.ok) throw new Error(`Google Fonts CSS: HTTP ${res.status}`);
  const faces = parseFaces(await res.text(), keep);
  if (faces.length === 0) throw new Error("no face found for the subsets asked; nothing written");
  mkdirSync(dir, { recursive: true });
  let out = `/* Self-hosted fonts (generated by devkit-fetch-fonts). Subsets: ${[...keep].join(", ")}.\n   ${c.header ?? ""}\n   font-display: ${display}. */\n\n`;
  const files = [];
  for (const f of faces) {
    const file = `${f.family.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${f.subset}.woff2`;
    const r = await fetch(f.url, {
      headers: { "User-Agent": UA },
      signal: AbortSignal.timeout(30_000),
    });
    if (!r.ok) throw new Error(`${f.url}: HTTP ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    writeFileSync(join(dir, file), buf);
    files.push({ file, bytes: buf.length });
    out +=
      `@font-face {\n  font-family: '${f.family}';\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n` +
      `  font-display: ${display};\n  src: url('${prefix}${file}') format('woff2');\n  unicode-range: ${f.unicode};\n}\n\n`;
  }
  writeFileSync(c.css ?? "app/fonts.css", out);
  console.log(`Wrote ${c.css ?? "app/fonts.css"} and ${files.length} woff2 files:`);
  for (const f of files) console.log(`  ${f.file}  ${(f.bytes / 1024).toFixed(1)} KB`);
}

if (isMain(import.meta.url)) await main();
